"""Generate ``leasespy/_iana_dhcp.py`` from IANA's bootp-dhcp-parameters registry file.

    python tools/gen_iana_dhcp.py PATH/TO/bootp-dhcp-parameters.xml --last-modified "Tue, 13 Oct 2026 20:07:04 GMT"
    python tools/gen_iana_dhcp.py --check          # compare the committed table with $PRIMARYSOURCE_HOME

The XML comes from ``primarysource iana import bootp-dhcp-parameters`` (which stores it byte for
byte under ``$PRIMARYSOURCE_HOME/iana/``) or from
https://www.iana.org/assignments/bootp-dhcp-parameters/bootp-dhcp-parameters.xml directly. The
generator never fetches. Citations elsewhere in this repository use the primarysource form
``iana:bootp-dhcp-parameters§options#53``.

IANA's Protocol Registries are CC0 1.0 under https://www.iana.org/help/licensing-terms, so the
generated table may be committed. It keeps the registry's own words for names and lengths, and
records the file's sha256, the registry's ``updated`` date and the HTTP ``Last-Modified``.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NS = {"a": "http://www.iana.org/assignments"}
URL = "https://www.iana.org/assignments/bootp-dhcp-parameters/bootp-dhcp-parameters.xml"
OUT = Path(__file__).resolve().parent.parent / "leasespy" / "_iana_dhcp.py"


def _text(node: ET.Element | None) -> str:
    return " ".join((node.text or "").split()) if node is not None else ""


def _refs(record: ET.Element) -> tuple[str, ...]:
    found = []
    for xref in record.findall("a:xref", NS):
        data = xref.get("data") or ""
        if xref.get("type") == "rfc" and re.fullmatch(r"rfc\d+", data):
            found.append(f"RFC {data[3:]}")
    return tuple(found)


def _registry(root: ET.Element, ident: str) -> ET.Element:
    for registry in root.findall("a:registry", NS):
        if registry.get("id") == ident:
            return registry
    raise SystemExit(f"registry {ident!r} not in the file")


def build(raw: bytes, last_modified: str, fetched: str) -> str:
    if b"<!DOCTYPE" in raw or b"<!ENTITY" in raw:
        raise SystemExit("refusing a file with a DOCTYPE or entity declaration")
    root = ET.fromstring(raw)  # noqa: S314 - no DTD, checked above
    updated = _text(root.find("a:updated", NS))
    options: dict[int, tuple[str, str, tuple[str, ...]]] = {}
    ranges: list[tuple[int, int, str]] = []
    for record in _registry(root, "options").findall("a:record", NS):
        value = _text(record.find("a:value", NS))
        name = _text(record.find("a:name", NS))
        length = _text(record.find("a:length", NS))
        if value.isdigit():
            options[int(value)] = (name, length, _refs(record))
        else:
            low, high = value.split("-")
            ranges.append((int(low), int(high), name))
    types: dict[int, tuple[str, tuple[str, ...]]] = {}
    for record in _registry(root, "message-type-53").findall("a:record", NS):
        types[int(_text(record.find("a:value", NS)))] = (
            _text(record.find("a:description", NS)),
            _refs(record),
        )
    lines = [
        '"""IANA DHCP option codes and message types. GENERATED by tools/gen_iana_dhcp.py: do not edit.',
        "",
        "Source: the IANA bootp-dhcp-parameters registry, a Protocol Registry released under CC0 1.0",
        "(https://www.iana.org/help/licensing-terms). The names and length strings are IANA's words.",
        "A name here says what IANA calls the code; it is not a statement that leasespy decodes it.",
        "Cite rows as ``iana:bootp-dhcp-parameters§options#<code>`` (primarysource form).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "SOURCE = {",
        f'    "url": "{URL}",',
        f'    "registry_updated": "{updated}",',
        f'    "last_modified": "{last_modified}",',
        f'    "fetched": "{fetched}",',
        f'    "sha256": "{hashlib.sha256(raw).hexdigest()}",',
        f'    "size": {len(raw)},',
        '    "licence": "CC0-1.0",',
        "}",
        "",
        "#: code -> (name, length as IANA writes it, RFCs that IANA cites)",
        "OPTIONS: dict[int, tuple[str, str, tuple[str, ...]]] = {",
    ]
    for code in sorted(options):
        lines.append(f"    {code}: {options[code]!r},")
    lines += [
        "}",
        "",
        "#: (first, last, name) spans IANA lists as unassigned, removed or private use",
        "OPTION_RANGES: tuple[tuple[int, int, str], ...] = (",
    ]
    for low, high, name in ranges:
        lines.append(f"    {(low, high, name)!r},")
    lines += [
        ")",
        "",
        "#: DHCP message type (option 53) -> (name, RFCs)",
        "MESSAGE_TYPES: dict[int, tuple[str, tuple[str, ...]]] = {",
    ]
    for code in sorted(types):
        lines.append(f"    {code}: {types[code]!r},")
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("xml", nargs="?", type=Path)
    parser.add_argument("--last-modified", default="")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        home = os.environ.get("PRIMARYSOURCE_HOME")
        path = Path(home) / "iana" / "bootp-dhcp-parameters.xml" if home else None
        if path is None or not path.exists():
            print("no primarysource copy of bootp-dhcp-parameters.xml: nothing to compare")
            return 0
        raw = path.read_bytes()
        committed = OUT.read_text(encoding="utf-8")
        if hashlib.sha256(raw).hexdigest() in committed:
            print("committed table was generated from this exact file")
            return 0
        print("the registry file differs from the committed table: regenerate and review")
        return 1
    if args.xml is None:
        parser.error("give the XML file")
    raw = args.xml.read_bytes()
    fetched = datetime.datetime.now(datetime.UTC).date().isoformat()
    OUT.write_text(build(raw, args.last_modified, fetched), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
